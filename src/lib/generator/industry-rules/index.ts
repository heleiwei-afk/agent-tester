/**
 * 获取行业规则文本
 */
export function getIndustryRules(industry: Industry): string {
  return INDUSTRY_RULES[industry] || '';
}

/**
 * 获取行业中文名称
 */
export function getIndustryName(industry: Industry): string {
  const names: Record<Industry, string> = {
    education: '教育',
    finance: '金融',
    medical: '医疗',
    customer_service: '客服',
    general: '通用',
  };
  return names[industry] || '通用';
}
